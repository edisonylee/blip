import SwiftUI

enum ThemePreference: String, CaseIterable, Identifiable {
    case system, light, dark

    var id: String { rawValue }

    var label: String {
        switch self {
        case .system: return "System"
        case .light:  return "Light"
        case .dark:   return "Dark"
        }
    }

    var icon: String {
        switch self {
        case .system: return "circle.lefthalf.filled"
        case .light:  return "sun.max.fill"
        case .dark:   return "moon.fill"
        }
    }

    /// `nil` tells SwiftUI to follow the OS setting.
    var colorScheme: ColorScheme? {
        switch self {
        case .system: return nil
        case .light:  return .light
        case .dark:   return .dark
        }
    }
}

/// Contract for theme management. Depend on this in views and ViewModels
/// so the concrete Firebase-free logic stays replaceable/testable.
@MainActor
protocol ThemeManagerProtocol: ObservableObject {
    var preference: ThemePreference { get set }
}
